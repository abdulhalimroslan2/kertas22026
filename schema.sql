-- 1. Cipta Jadual Kod Lesen
CREATE TABLE IF NOT EXISTS public.license_keys (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    key TEXT UNIQUE NOT NULL,
    order_id TEXT DEFAULT 'Shopee Order',
    customer_name TEXT DEFAULT 'Pelanggan Shopee',
    downloads_left INTEGER DEFAULT 2 CHECK (downloads_left >= 0),
    max_downloads INTEGER DEFAULT 2,
    download_count INTEGER DEFAULT 0,
    status TEXT DEFAULT 'active',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    last_download_at TIMESTAMP WITH TIME ZONE
);

-- 2. Cipta Index untuk Carian Pantas mengikut Kod
CREATE INDEX IF NOT EXISTS idx_license_keys_key ON public.license_keys (UPPER(key));

-- 3. Dayakan Row Level Security (RLS)
ALTER TABLE public.license_keys ENABLE ROW LEVEL SECURITY;

-- 4. Polisi Keselamatan (Policy):
DROP POLICY IF EXISTS "Benarkan Anon Semak Kunci" ON public.license_keys;
CREATE POLICY "Benarkan Anon Semak Kunci" 
ON public.license_keys 
FOR SELECT 
TO anon, authenticated 
USING (true);

DROP POLICY IF EXISTS "Benarkan Kemas Kini Kuota" ON public.license_keys;
CREATE POLICY "Benarkan Kemas Kini Kuota" 
ON public.license_keys 
FOR UPDATE 
TO anon, authenticated 
USING (true)
WITH CHECK (true);

DROP POLICY IF EXISTS "Benarkan Tambah Kunci Baharu" ON public.license_keys;
CREATE POLICY "Benarkan Tambah Kunci Baharu" 
ON public.license_keys 
FOR INSERT 
TO anon, authenticated 
WITH CHECK (true);

DROP POLICY IF EXISTS "Benarkan Padam Kunci" ON public.license_keys;
CREATE POLICY "Benarkan Padam Kunci" 
ON public.license_keys 
FOR DELETE 
TO anon, authenticated 
USING (true);

-- 5. Fungsi Atomik (RPC) untuk Tolak Kuota Muat Turun Secara Selamat
CREATE OR REPLACE FUNCTION public.decrement_download(p_key TEXT)
RETURNS JSON
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    v_record public.license_keys%ROWTYPE;
BEGIN
    SELECT * INTO v_record
    FROM public.license_keys
    WHERE UPPER(key) = UPPER(p_key)
    FOR UPDATE;

    IF NOT FOUND THEN
        RETURN json_build_object(
            'success', false,
            'message', 'Kod lesen tidak sah atau tidak dijumpai.'
        );
    END IF;

    IF v_record.status = 'disabled' THEN
        RETURN json_build_object(
            'success', false,
            'message', 'Kod lesen telah dinyahaktifkan oleh pihak penjual.'
        );
    END IF;

    IF v_record.downloads_left <= 0 THEN
        UPDATE public.license_keys
        SET status = 'exhausted'
        WHERE id = v_record.id;

        RETURN json_build_object(
            'success', false,
            'message', 'Had muat turun (2 kali) telah habis digunakan.',
            'downloads_left', 0
        );
    END IF;

    UPDATE public.license_keys
    SET 
        downloads_left = downloads_left - 1,
        download_count = download_count + 1,
        last_download_at = timezone('utc'::text, now()),
        status = CASE WHEN (downloads_left - 1) <= 0 THEN 'exhausted' ELSE 'active' END
    WHERE id = v_record.id
    RETURNING * INTO v_record;

    RETURN json_build_object(
        'success', true,
        'message', 'Muat turun dibenarkan. Kuota berjaya ditolak.',
        'downloads_left', v_record.downloads_left,
        'download_count', v_record.download_count,
        'max_downloads', v_record.max_downloads,
        'key', v_record.key,
        'status', v_record.status
    );
END;
$$;

